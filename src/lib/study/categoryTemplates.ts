// === המרת מספר לגמטריה ===
const ONES = ["", "א", "ב", "ג", "ד", "ה", "ו", "ז", "ח", "ט"];
const TENS = ["", "י", "כ", "ל", "מ", "נ", "ס", "ע", "פ", "צ"];
const HUNDREDS = ["", "ק", "ר", "ש", "ת"];

function toGematria(n: number): string {
  if (n <= 0) return "";
  let result = "";
  // מאות
  const h = Math.floor(n / 100);
  n = n % 100;
  // טו = ט"ו, טז = ט"ז (חריגים)
  if (h > 0) {
    if (h <= 4) result += HUNDREDS[h];
    else {
      // 500=תק, 600=תר, 700=תש, 800=תת, 900=תתק
      let rem = h;
      while (rem >= 4) { result += "ת"; rem -= 4; }
      if (rem > 0) result += HUNDREDS[rem];
    }
  }
  if (n === 15) { result += "ט\u05f4ו"; return result; }
  if (n === 16) { result += "ט\u05f4ז"; return result; }
  const t = Math.floor(n / 10);
  const o = n % 10;
  const core = TENS[t] + ONES[o];
  if (core.length === 0) return result;
  if (core.length === 1) return result + core;
  // הוסף גרשיים לפני האות האחרונה
  return result + core.slice(0, -1) + "\u05f4" + core.slice(-1);
}

/** בונה מערך תת-קטגוריות "סימן X" לפי טווח [start, end] */
function simanChildren(start: number, end: number): CategoryTemplateNode[] {
  const arr: CategoryTemplateNode[] = [];
  for (let i = start; i <= end; i++) {
    arr.push({ name: `סימן ${toGematria(i)}` });
  }
  return arr;
}

/** קיצור לבניית node עם ילדי סימנים (ללא סעיפים) */
function hl(name: string, start: number, end: number): CategoryTemplateNode {
  return { name, children: simanChildren(start, end) };
}

