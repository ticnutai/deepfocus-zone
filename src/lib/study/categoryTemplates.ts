/** בונה node של סימן יחיד עם ילדי סעיפים לפי מערך הנתונים */
function simanNodeWithSeifim(n: number, seifimArr: number[]): CategoryTemplateNode {
  const count = seifimArr[n - 1] ?? 0;
  if (count <= 1) return { name: `סימן ${toGematria(n)}` };
  return {
    name: `סימן ${toGematria(n)}`,
    children: Array.from({ length: count }, (_, j) => ({ name: `סעיף ${toGematria(j + 1)}` })),
  };
}

/** בונה node של הלכה עם סימנים וסעיפים — seifimArr מ-Sefaria */
function hlS(name: string, start: number, end: number, seifimArr: number[]): CategoryTemplateNode {
  return {
    name,
    children: Array.from({ length: end - start + 1 }, (_, i) =>
      simanNodeWithSeifim(start + i, seifimArr)
    ),
  };
}

